import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import {
    createRecoveryChallenge,
    exportMyWallet,
    getLedger,
    getMyWallet,
    getTransactions,
    internalTransfer,
    lockEscrow,
    releaseEscrow,
    rotateWalletEncryption,
    slashEscrow
} from '../controllers/wallet.controller';
import { authenticateJWT, restrictTo } from '../middleware/auth.middleware';
import { paymentRateLimiter, publicRateLimiter } from '../middleware/rate-limit.middleware';

const router: Router = Router();

const walletRecoveryLimiter = rateLimit({
    windowMs: 15 * 60 * 1000,
    max: process.env.NODE_ENV === 'test' ? 1000 : 5,
    standardHeaders: true,
    legacyHeaders: false,
    message: {
        error: {
            code: 'WALLET_RECOVERY_RATE_LIMIT',
            message: 'Too many wallet recovery attempts. Please try again later.'
        }
    }
});

router.use(authenticateJWT);

/**
 * @openapi
 * /v1/wallets/me:
 *   get:
 *     summary: Get My Wallet
 *     tags: [Wallet]
 *     security:
 *       - bearerAuth: []
 *     responses:
 *       '200':
 *         description: Successful response
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *       '401':
 *         description: Authentication required
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       '429':
 *         description: Rate limit exceeded
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/RateLimitError'
 *       '500':
 *         description: Internal server error
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 */
router.get('/me', publicRateLimiter, getMyWallet);
