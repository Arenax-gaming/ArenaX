/**
 * @openapi
 * /v1/admin/confirmations:
 *   post:
 *     summary: Request a confirmation token for destructive/bulk actions
 *     tags: [Admin]
 *     description: Requires role ADMIN.
 *     security:
 *       - bearerAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             properties:
 *               action:
 *                 type: string
 *               payload:
 *                 type: object
 *               ttlMs:
 *                 type: string
 *     responses:
 *       '200':
 *         description: Successful response
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *       '400':
 *         description: Invalid request
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       '401':
 *         description: Authentication required
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       '403':
 *         description: Forbidden
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       '429':
 *         description: Rate limit exceeded
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/RateLimitError'
 *       '500':
 *         description: Internal server error
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 */
router.post('/confirmations', authenticateJWT, restrictToScope('admin:write'), (req, res) => {
    const { action, payload, ttlMs } = req.body as any
    if (!action) return res.status(400).json({ error: 'action is required' })
    const info = confirmationService.generate(req.user!.id, action, payload, ttlMs)
    res.status(200).json({ token: info.token, expiresAt: info.expiresAt })
})
