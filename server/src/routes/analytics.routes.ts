/**
 * @openapi
 * /v1/analytics/aggregated:
 *   get:
 *     summary: ── Data Aggregation Endpoints (Issue 689) ──────────────────────────────────────
 *     tags: [Analytics]
 *     security:
 *       - bearerAuth: []
 *     parameters:
 *       - in: query
 *         name: period
 *         required: false
 *         schema:
 *           type: string
 *     responses:
 *       '200':
 *         description: Successful response
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *       '400':
 *         description: Invalid request
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       '401':
 *         description: Authentication required
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       '403':
 *         description: Forbidden
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       '500':
 *         description: Internal server error
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 */
router.get(
    '/aggregated',
    requirePermission('analytics:read'),
    async (req, res) => {
        const period = (req.query.period as AnalyticsPeriod) || '24h';
        const metrics = await defaultAnalyticsService.getAggregatedMetrics(period);
        res.json(metrics);
    }
);

