/**
 * @openapi
 * /v1/analytics/privacy:
 *   get:
 *     summary: Get analytics privacy
 *     tags: [Analytics]
 *     security:
 *       - bearerAuth: []
 *     parameters:
 *       - in: query
 *         name: metrics
 *         required: false
 *         schema:
 *           type: string
 *       - in: query
 *         name: epsilon
 *         required: false
 *         schema:
 *           type: string
 *     responses:
 *       '200':
 *         description: Successful response
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *       '400':
 *         description: Invalid request
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       '401':
 *         description: Authentication required
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       '403':
 *         description: Forbidden
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       '500':
 *         description: Internal server error
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 */
router.get(
    '/privacy',
    requirePermission('analytics:read'),
    async (req, res) => {
        const names = (req.query.metrics as string)?.split(',') || [
            'total_matches',
            'unique_players',
            'total_volume',
        ];
        const epsilon = parseFloat(req.query.epsilon as string) || 1.0;
        const metrics = await defaultAnalyticsService.getPrivacyPreservingMetrics(names, epsilon);
        res.json({ metrics });
    }
);

